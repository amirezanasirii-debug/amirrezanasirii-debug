        isnadChain: String,
        sourceReference: String,
        grade: String
    ): HadithEntity {
        val searchCombined = "$textArabic $textPersian $isnadChain $sourceReference"
        return HadithEntity(
            id = id,
            bookId = bookId,
            chapterId = chapterId,
            collection = collection,
            numberInBook = numberInBook,
            textArabic = textArabic,
            textPersian = textPersian,
            isnadChain = isnadChain,
            sourceReference = sourceReference,
            grade = grade,
            searchableText = HadithTextNormalizer.normalize(searchCombined)
        )
    }

